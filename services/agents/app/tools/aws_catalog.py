"""Loader for the closed-vocabulary AWS resource catalog (app/tools/schemas/aws_services.json,
generated by `npm run gen:agent-schemas` from src/data/awsServices.ts — never hand-edited). M0/M1
generated this file but nothing consumed it; app/changeplan.py's gate is the first consumer,
using it to reject any add_node proposal citing a service_id the model invented."""

import json
from functools import lru_cache
from pathlib import Path

_CATALOG_PATH = Path(__file__).parent / "schemas" / "aws_services.json"


@lru_cache
def _catalog() -> dict:
    return json.loads(_CATALOG_PATH.read_text(encoding="utf-8"))


@lru_cache
def valid_service_ids() -> frozenset[str]:
    return frozenset(_catalog().get("serviceIds", []))


def service_fields(service_id: str) -> dict:
    return _catalog().get("services", {}).get(service_id, {}).get("fields", {})
